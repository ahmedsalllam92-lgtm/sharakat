function stratAutoChecks(p, key, txt) {
  txt = txt || stratText(p);
  return stratItems(key).map((it) => (typeof it.test === 'function' ? it.test(p) : it.test instanceof RegExp ? it.test.test(txt) : false));
}
const stratPct = (checks) => (checks && checks.length ? checks.filter(Boolean).length / checks.length : 0);
/* المفتاح ← { الهدف، المبادرة، الاسم } */
function stratTarget(key) {
  const [g, i] = String(key || '').split('.');
  const goal = stratGoals().find((x) => x.k === g); if (!goal) return null;
  const init = i ? goal.inits.find((x) => x.c === key) : null;
  return { key, goal, init, label: init ? init.t : goal.t, kind: init ? 'مبادرة' : 'هدف' };
}
/* أفضل هدف أو مبادرة للشراكة من نصوصها: المبادرة أدق من الهدف، والتعادل يُحسم بعدد الكلمات المطابقة */
function stratSuggest(p) {
  const txt = stratText(p); let best = null;
  stratGoals().forEach((g) => [...g.inits.map((i) => i.c), g.k].forEach((key) => {
    const ch = stratAutoChecks(p, key, txt), pc = stratPct(ch);
    const hits = stratItems(key).reduce((t, it) => t + (it.test instanceof RegExp ? (txt.match(new RegExp(it.test.source, 'g')) || []).length : it.test && it.test(p) ? 3 : 0), 0);
    const sc = pc * 100 + Math.min(hits, 40) * 0.5 + (key.includes('.') ? 2 : 0) - (key.startsWith('EO') ? 6 : 0) - (/^SO3\.I4$/.test(key) ? 6 : 0);
    if (!best || sc > best.sc) best = { key, checks: ch, sc };
  }));
  return best ? { target: best.key, checks: best.checks, src: 'auto' } : null;
}
/* تقييم الشراكة الحالي: المعتمد إن وُجد، وإلا المقترح الآلي */
function stratAssessOf(p) {
  if (p.stratAssess && stratTarget(p.stratAssess.target)) return p.stratAssess;
  const sd = STRAT_SEED[p.code];
  if (sd && stratTarget(sd[0]) && stratItems(sd[0]).length === sd[1].length) return { target: sd[0], checks: sd[1].split('').map((c) => c === '1'), src: 'auto' };
  if (!p._sgSug || p._sgSug.v !== (p.updatedAt || '') + '|' + JSON.stringify((D.settings && D.settings.stratCrit) || {}).length) {
    const s = stratSuggest(p);
    Object.defineProperty(p, '_sgSug', { value: { v: (p.updatedAt || '') + '|' + JSON.stringify((D.settings && D.settings.stratCrit) || {}).length, s }, configurable: true, enumerable: false, writable: true });
  }
  return p._sgSug.s;
}
