import asyncio, json, base64
from playwright.async_api import async_playwright
URL='file:///home/claude/shots/app.html'
PDF = b'%PDF-1.4\n1 0 obj<<>>endobj\ntrailer<<>>\n%%EOF'
R=[]
def ok(n,c,x=''): R.append(c); print('PASS' if c else 'FAIL', n, x, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await (await b.new_context(viewport={'width':1440,'height':900})).new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_selector('#main .page'); await pg.wait_for_timeout(600)
        E=pg.evaluate
        async def go(h): await E(f"location.hash==={json.dumps(h)} ? route() : (location.hash={json.dumps(h)})"); await pg.wait_for_timeout(800)
        async def acc(a): await E(f"switchAccount({json.dumps(a)})"); await pg.wait_for_timeout(700)
        async def open_step(sid): await pg.click(f'[data-wfopen="{sid}"]'); await pg.wait_for_selector('.wf-modal'); await pg.wait_for_timeout(250)
        async def upload(doc, name='doc.pdf'):
            await pg.set_input_files(f'.wf-modal [data-wfup="{doc}"]', files=[{'name':name,'mimeType':'application/pdf','buffer':PDF}]); await pg.wait_for_timeout(900)
        async def do(act, note=''):
            if note: await pg.fill('#wfNote', note)
            await pg.click(f'.wf-modal [data-wfdo="{act}"]'); await pg.wait_for_timeout(800)
        cur = lambda: E("(()=>{const x=App.route.name==='proposal'?D.proposals.find(y=>y.id===App.route.params.id):D.partnerships.find(y=>y.id===App.route.params.id);const s=wfStateOf(App.route.name==='proposal'?'proposal':'partnership',x).cur;return s&&s.id})()")
        # — الحسابات —
        A = await E("wfAccounts().map(a=>a.id)")
        depts = await E("L('departments').filter(d=>d!==D.settings.org.dept)")
        ok('an account for every department', all(('dept:'+d) in A for d in depts), len(A))
        ok('legal affairs added as a department', 'الإدارة القانونية' in depts)
        ok('excellency office account', 'dept:مكتب المعالي' in A)
        ok('one account per partnerships team member + admin + leadership', 'admin' in A and 'viewer' in A and sum(1 for a in A if a.startswith('team:')) == await E("L('team').length"))
        await pg.click('#topbar [data-role]'); await pg.wait_for_selector('.modal [data-acc]')
        ok('account switcher lists accounts grouped', await E("document.querySelectorAll('.modal .acc-g').length") >= 3 and await E("document.querySelectorAll('.modal [data-acc]').length") == len(A))
        await pg.click('.modal [data-acc="dept:الإدارة القانونية"]'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(800)
        ok('switching account sets role and department', await E("Session.role()") == 'dept' and await E("Session.dept()") == 'الإدارة القانونية' and 'الإدارة القانونية' in await E("document.querySelector('#topbar [data-role]').textContent"))
        # — الطلب: منهجية ثم تقييم —
        await acc('dept:الإدارة العامة للمشاريع')
        pid = await E("D.proposals.find(x=>x.status==='submitted'&&x.department==='الإدارة العامة للمشاريع').id")
        await go(f'#/proposals/{pid}')
        ok('proposal page shows the 13-step track', await E("document.querySelectorAll('.wf-sec .wf-s').length") == 13)
        ok('requesting department cannot run the evaluation', not await E("!!document.querySelector('[data-wfopen]')"))
        await acc('team:وعد')
        ok('team task list includes the methodology step', await E(f"wfTasks().some(t=>t.rec.id==='{pid}'&&t.step.id==='method')"))
        await go(f'#/proposals/{pid}')
        await pg.click('[data-act="accepted"]'); await pg.wait_for_selector('.wf-modal'); await pg.wait_for_timeout(250)
        ok('accepting first requires the methodology and evaluation', 'منهجية' in await E("document.querySelector('.wf-modal .modal-h h3').textContent"))
        await pg.click('.wf-modal [data-wfdo="done"]'); await pg.wait_for_timeout(400)
        ok('cannot complete without the required form', await cur() == 'method')
        await upload('methodology', 'منهجية.pdf'); await do('done')
        ok('methodology done; proposal moves to review', await cur() == 'eval' and await E(f"D.proposals.find(x=>x.id==='{pid}').status") == 'review')
        await open_step('eval'); await upload('evaluation', 'تقييم.pdf'); await do('yes', 'الجهة مناسبة لأهداف التشجير.')
        ok('«الجهة مناسبة» accepts the proposal', await E(f"D.proposals.find(x=>x.id==='{pid}').status") == 'accepted')
        ok('conversion task appears for the team', await E(f"wfTasks().some(t=>t.rec.id==='{pid}'&&t.step.id==='convert')"))
        await pg.click('[data-act="convert"]'); await pg.wait_for_selector('.modal .map-tbl'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(1200)
        ptid = await E("App.route.params.id")
        ok('converted partnership starts at the kickoff meeting (step 4)', await cur() == 'meeting' and await E(f"D.partnerships.find(x=>x.id==='{ptid}').requesterDept") == 'الإدارة العامة للمشاريع')
        ok('steps 2–3 carry over with their documents', await E("document.querySelectorAll('.wf-s.done').length") == 3 and await E("document.querySelectorAll('.wf-s.done .wf-doc').length") == 2)
        # — الاجتماع والمسودة —
        await open_step('meeting')
        await pg.fill('#wfDate', '2026-11-10'); await pg.fill('#wfInt', 'زيادة الغطاء النباتي في المواقع البعيدة.')
        await pg.check('.wf-modal input[name=wfAtt][value="الإدارة العامة للاتصال المؤسسي"]')
        await do('done')
        ok('meeting recorded; supporting departments join the partnership', await cur() == 'draft' and 'الإدارة العامة للاتصال المؤسسي' in await E(f"D.partnerships.find(x=>x.id==='{ptid}').departments"))
        await open_step('draft'); await upload('draft', 'مسودة.docx'); await pg.fill('#wfCoop', '1. تنفيذ أعمال التشجير.\n2. توفير المعدات.'); await do('done')
        ok('draft built; cooperation areas copied to the record', await cur() == 'depts' and 'تنفيذ أعمال التشجير' in await E(f"D.partnerships.find(x=>x.id==='{ptid}').cooperationAreas"))
        # — ملاحظات الإدارات من حساباتها —
        await acc('dept:الإدارة العامة للمشاريع')
        ok('concerned department gets a task', await E(f"wfTasks().some(t=>t.rec.id==='{ptid}'&&t.step.id==='depts')"))
        await go(f'#/partnerships/{ptid}')
        ok('department can see the draft document', await E("[...document.querySelectorAll('.wf-doc')].some(d=>d.textContent.includes('مسودة'))"))
        await open_step('depts'); await do('dept', 'لا ملاحظات جوهرية.')
        ok('first department notes recorded, step still open', await cur() == 'depts' and await E(f"wfTasks().every(t=>!(t.rec.id==='{ptid}'&&t.step.id==='depts'))"))
        await acc('dept:الإدارة العامة للاتصال المؤسسي'); await go(f'#/partnerships/{ptid}')
        await open_step('depts'); await do('dept', 'إضافة بند للتغطية الإعلامية.')
        ok('all concerned departments replied → step closes', await cur() == 'strategy')
        # — المواءمة الاستراتيجية: إعادة ثم اعتماد —
        await acc('team:وعد'); await go(f'#/partnerships/{ptid}')
        ok('team cannot approve on behalf of strategy', not await E("!!document.querySelector('[data-wfopen=\"strategy\"]')") or 'اعتماد' not in await E("document.querySelector('[data-wfopen=\"strategy\"]').textContent"))
        await acc('dept:الإدارة العامة للاستراتيجية'); await go(f'#/partnerships/{ptid}')
        await open_step('strategy'); await do('return', 'يلزم ربط البند الثاني بالهدف الاستراتيجي الثالث.')
        ok('strategy returns with notes', await E(f"wfStateOf('partnership', D.partnerships.find(x=>x.id==='{ptid}')).S.strategy.status") == 'returned')
        await open_step('strategy'); await upload('alignment', 'مواءمة.pdf'); await do('yes')
        ok('strategy approves with the alignment form', await cur() == 'partner')
        # — الشريك ثم القانونية —
        await acc('team:وعد'); await go(f'#/partnerships/{ptid}')
        await open_step('partner'); await upload('partnerVersion', 'بعد-الشريك.docx'); await do('done')
        ok('after partner notes the partnership awaits signing', await cur() == 'legal' and await E(f"D.partnerships.find(x=>x.id==='{ptid}').stage") == 'sign')
        await acc('dept:الإدارة القانونية'); await go(f'#/partnerships/{ptid}')
        await open_step('legal'); await upload('legalReview', 'مراجعة.pdf'); await do('yes')
        ok('legal cannot approve before the letter is uploaded', await cur() == 'legal')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await acc('team:وعد')
        ok('team gets a task to upload the letter', await E(f"wfTasks().some(t=>t.rec.id==='{ptid}'&&t.step.id==='legal')"))
        await go(f'#/partnerships/{ptid}'); await open_step('legal'); await upload('letter', 'خطاب.pdf'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await acc('dept:الإدارة القانونية'); await go(f'#/partnerships/{ptid}'); await open_step('legal'); await do('yes')
        ok('legal approves the letter', await cur() == 'excellency')
        # — المعالي —
        await acc('team:وعد'); await go(f'#/partnerships/{ptid}'); await open_step('excellency'); await upload('transaction', 'المعاملة.pdf'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await acc('dept:مكتب المعالي'); await go(f'#/partnerships/{ptid}'); await open_step('excellency'); await do('yes')
        ok('excellency approval recorded', await cur() == 'signed')
        # — التوقيع —
        await acc('team:وعد'); await go(f'#/partnerships/{ptid}'); await open_step('signed'); await upload('signedMoU', 'موقعة.pdf')
        await pg.fill('#wfStart', '2026-11-01'); await pg.fill('#wfEnd', '2028-10-31'); await do('done')
        rec = await E(f"(()=>{{const p=D.partnerships.find(x=>x.id==='{ptid}');return [p.stage,p.startDate,p.endDate,pStatus(p)]}})()")
        ok('signed MoU makes the partnership signed and active', rec == ['signed','2026-11-01','2028-10-31','active'], rec)
        # — التفعيل —
        await acc('dept:إدارة تطوير الأعمال')
        ok('business development gets the activation task', await E(f"wfTasks().some(t=>t.rec.id==='{ptid}'&&t.step.id==='bizdev')"))
        await go(f'#/partnerships/{ptid}'); await open_step('bizdev'); await upload('activationPlan', 'خطة.pdf'); await do('done')
        ok('activation plan → «قيد التفعيل»', await E(f"D.partnerships.find(x=>x.id==='{ptid}').activation") == 'قيد التفعيل')
        await acc('dept:الإدارة العامة للمشاريع'); await go(f'#/partnerships/{ptid}'); await open_step('reports'); await do('dept')
        ok('activation report needs its file', await E(f"D.partnerships.find(x=>x.id==='{ptid}').activation") == 'قيد التفعيل')
        await upload('activationReport', 'تقرير.pdf'); await do('dept', 'نُفذت المرحلة الأولى.')
        ok('first activation report → «مفعّلة»', await E(f"D.partnerships.find(x=>x.id==='{ptid}').activation") == 'مفعّلة')
        ok('every step is logged in the audit trail', await E(f"D.audit.filter(a=>a.entityId==='{ptid}'&&a.action.startsWith('workflow')).length") >= 12)
        ok('workflow documents stored as partnership files', await E(f"D.partnerships.find(x=>x.id==='{ptid}').attachments.filter(a=>a.category===WF_CAT).length") >= 9)
        # — الاطلاع والمهام —
        await acc('viewer')
        ok('leadership account has no tasks and no action buttons', await E("wfTasks().length") == 0 and not await E("!!document.querySelector('[data-wfopen].primary, [data-wfopen].gold')"))
        await acc('dept:الإدارة القانونية'); await go('#/tasks')
        ok('«مهامي» page lists tasks with their steps', await E("document.querySelectorAll('.tk').length") == await E("wfTasks().length"))
        ok('nav shows the task count', await E("+(document.querySelector('.nav-a[href=\"#/tasks\"] .cnt')||{textContent:0}).textContent") == await E("wfTasks().filter(t=>!t.follow).length"))
        # — السجلات السابقة —
        await acc('admin')
        ok('existing signed records start at activation planning', await E("wfStateOf('partnership', D.partnerships.find(p=>partnerName(p).includes('حرس'))).cur.id") == 'bizdev')
        # — الإعدادات —
        await go('#/settings/roles')
        ok('settings list department accounts and their steps', await E("document.querySelectorAll('.acc-tbl tbody tr').length") == len(A))
        await pg.select_option('[data-wfdept="legal"]', 'الإدارة العامة للمشاريع'); await pg.wait_for_timeout(500)
        ok('reassigning the legal review moves the duty', await E("wfDept('legal')") == 'الإدارة العامة للمشاريع' and 'legal' in await E("wfAccounts().find(a=>a.id==='dept:الإدارة العامة للمشاريع').duties"))
        await pg.select_option('[data-wfdept="legal"]', 'الإدارة القانونية'); await pg.wait_for_timeout(500)
        await pg.set_input_files('[data-tplup="evaluation"]', files=[{'name':'نموذج-التقييم.docx','mimeType':'application/octet-stream','buffer':b'x'}]); await pg.wait_for_timeout(600)
        ok('blank template uploaded', await E("!!D.settings.wfTemplates.evaluation"))
        pid2 = await E("D.proposals.find(x=>x.status==='review').id"); await go(f'#/proposals/{pid2}')
        await pg.click('[data-wfopen]'); await pg.wait_for_selector('.wf-modal'); await pg.keyboard.press('Escape')
        await open_step('method'); await upload('methodology'); await do('done')
        await open_step('eval')
        ok('step dialog offers the blank template', await E("!!document.querySelector('.wf-modal [data-wftpl]')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # — مسار الشراكة —
        await go('#/process')
        ok('process map generated from the applied workflow (13 numbered steps)', await E("document.querySelectorAll('.pr-node .pr-num').length") == 13)
        ok('seven lanes incl. strategy, legal, excellency, business development', await E("document.querySelectorAll('.pr-lane-h').length") == 7)
        ok('no page errors', not errs, errs[:3])
        await b.close()
    print(f'\n{sum(R)}/{len(R)} passed')
asyncio.run(main())
