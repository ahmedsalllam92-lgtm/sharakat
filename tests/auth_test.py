import asyncio, json, os
# كلمات المرور لا تُكتب في المستودع: ملف محلي يُمرَّر بالمتغير SHK_TEST_PW
PW = json.load(open(os.environ['SHK_TEST_PW']))
from playwright.async_api import async_playwright
URL='file:///home/claude/shots/app.html'
R=[]
def ok(n,c,x=''): R.append(bool(c)); print('PASS' if c else 'FAIL', n, x, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':1440,'height':900})
        await ctx.add_init_script("localStorage.setItem('shk_auth_force','1')")
        pg = await ctx.new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        E = pg.evaluate
        async def login(acc, pw):
            await pg.wait_for_selector('#shkLogin #lgPw')
            await pg.fill('#lgUser', await pg.evaluate("(id)=>accUser(authAccounts().find(a=>a.id===id))", acc)); await pg.fill('#lgPw', pw); await pg.click('#shkLogin .lg-go'); await pg.wait_for_timeout(700)
        async def logout():
            await E("authLogout()"); await pg.wait_for_timeout(500)
        await pg.goto(URL); await pg.wait_for_timeout(800)
        ok('login screen before any data is shown', await E("!!document.getElementById('shkLogin') && !document.querySelector('#main .page')"))
        accs = await E("[...accUsers().keys()]")
        ok('accounts: system admin, partnerships, team, departments, viewer', accs[0]=='sysadmin' and 'admin' in accs and any(a.startswith('team:') for a in accs) and any(a.startswith('dept:') for a in accs) and 'viewer' in accs, len(accs))
        await login('admin', 'wrong')
        ok('wrong password rejected', await E("document.getElementById('lgErr').textContent.includes('غير صحيحة') && !document.querySelector('#main .page')"))
        await login('admin', PW['admin'])
        ok('partnerships account logs in with full permissions', await E("!document.getElementById('shkLogin') && !!document.querySelector('#main .page') && can('manage.accounts') && can('delete.partnership') && can('manage.backup')"))
        ok('topbar shows the account, no simulation tag', await E("document.querySelector('#topbar .rolebox .rl').textContent==='إدارة الشراكات' && !document.querySelector('#topbar .tag-sim')"))
        await E("location.hash='#/settings/roles'"); await pg.wait_for_timeout(600)
        ok('passwords panel lists the system admin as protected', await E("(()=>{const r=document.querySelector('[data-pwrow=\"sysadmin\"]'); return !!r && !r.querySelector('[data-pwset]') && r.textContent.includes('محمية')})()"))
        ok('system admin password not stored anywhere in data', await E("!JSON.stringify(D.settings).includes('"+PW['sys']+"') && !(D.settings.auth&&D.settings.auth.pw&&D.settings.auth.pw.sysadmin)"))
        err = await E("authSetPassword('sysadmin','x1234').then(()=>'changed').catch(e=>e.message)")
        ok('nobody can change the system admin password', 'محمية' in err, err)
        ok('partnerships cannot preview other accounts', await E("(switchAccount('viewer'), Session.role())") == 'admin')
        # تعيين كلمة مرور لحساب إدارة
        dept = [a for a in accs if a.startswith('dept:')][0]
        await pg.click(f'[data-pwset="{dept}"]'); await pg.wait_for_selector('#pwNew')
        await pg.fill('#pwNew','legal99'); await pg.fill('#pwNew2','legal99'); await pg.click('.modal [data-ok]'); await pg.wait_for_timeout(500)
        ok('partnerships sets a department password (stored as hash)', await E(f"D.settings.auth.pw['{dept}']===pwHash('{dept}','legal99') && !JSON.stringify(D.settings.auth).includes('legal99')"))
        await logout()
        ok('logout returns to login screen', await E("!!document.getElementById('shkLogin') && !document.querySelector('#main .page')"))
        await login(dept, PW['dept'])
        ok('old default password no longer works', await E("!!document.getElementById('shkLogin')"))
        await login(dept, 'legal99')
        ok('department logs in with its new password', await E("Session.role()==='dept' && !can('manage.accounts') && !can('view.dashboard') && !can('edit.partnership')"))
        await E("location.hash='#/settings/roles'"); await pg.wait_for_timeout(600)
        ok('department sees only its own account panel', await E("!!document.querySelector('#setMyAcc') && !document.querySelector('#setPw') && !document.querySelector('[data-asacc]')"))
        await E("location.hash='#/settings/general'"); await pg.wait_for_timeout(500)
        ok('department cannot open restricted settings', await E("!document.querySelector('#gname')"))
        await E("location.hash='#/dashboard'"); await pg.wait_for_timeout(500)
        ok('department blocked from the dashboard', await E("!document.querySelector('.ob') && !!document.querySelector('#main .page')"))
        r = await E("authSetPassword('viewer','abcd').then(()=>'changed').catch(e=>e.message)")
        ok('department cannot change other passwords', 'صلاحية' in r, r)
        await logout()
        await login('viewer', PW['viewer'])
        ok('viewer: read only', await E("Session.role()==='viewer' && can('view.dashboard') && !can('edit.partnership') && !can('proposal.create')"))
        await logout()
        await login('sysadmin', PW['sys'])
        ok('system admin logs in', await E("isSysAdmin() && can('manage.accounts') && document.querySelector('#topbar .rolebox .rl').textContent==='مدير النظام'"))
        await pg.click('#topbar [data-role]'); await pg.wait_for_timeout(300)
        ok('system admin menu: preview, no password change', await E("!!document.querySelector('.acc-menu [data-am=\"as\"]') && !document.querySelector('.acc-menu [data-am=\"pw\"]')"))
        await pg.keyboard.press('Escape')
        await E("switchAccount('viewer')"); await pg.wait_for_timeout(500)
        ok('system admin previews as viewer', await E("Session.role()==='viewer'"))
        await pg.click('#topbar [data-role]'); await pg.wait_for_timeout(300)
        await pg.click('.acc-menu [data-am="back"]'); await pg.wait_for_timeout(500)
        ok('back to system admin', await E("isSysAdmin()"))
        await pg.reload(); await pg.wait_for_selector('#main .page, #shkLogin', timeout=15000); await pg.wait_for_timeout(400)
        ok('remembered session survives reload', await E("!document.getElementById('shkLogin') && isSysAdmin()"))
        await logout()
        for i in range(5): await login('admin','nope')
        await login('admin',PW['admin'])
        ok('locked for a while after 5 failures', await E("!!document.getElementById('shkLogin') && document.getElementById('lgErr').textContent.includes('محاولات')"))
        ok('no page errors', not errs, errs[:3])
        await b.close()
    print('SUMMARY', sum(R), '/', len(R))
asyncio.run(main())
