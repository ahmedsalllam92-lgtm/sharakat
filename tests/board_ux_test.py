import asyncio, json
from playwright.async_api import async_playwright
URL='file:///home/claude/shots/app.html'
R=[]
def ok(n,c,x=''): R.append(c); print('PASS' if c else 'FAIL', n, x, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await (await b.new_context(viewport={'width':1440,'height':900})).new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_selector('#main .page'); await pg.wait_for_timeout(600)
        E=pg.evaluate
        async def go(h): await E(f"location.hash==={json.dumps(h)} ? route() : (location.hash={json.dumps(h)})"); await pg.wait_for_timeout(900)
        await E("applyDesign('board')"); await pg.wait_for_timeout(1200)
        # — نافذة الوصول السريع —
        await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(400)
        ok('Ctrl+K opens the quick-access window', await E("!!document.querySelector('#pal') && document.activeElement.id==='palQ'"))
        ok('empty query shows actions and pages', await E("[...document.querySelectorAll('.pal-h')].map(h=>h.textContent).join('|')") in ('إجراءات|الصفحات','فتحته مؤخرًا|إجراءات'))
        await pg.keyboard.type('حرس'); await pg.wait_for_timeout(400)
        ok('typing finds partnerships and partners', 'الشراكات' in await E("[...document.querySelectorAll('.pal-h')].map(h=>h.textContent).join('|')") and 'حرس' in await E("document.querySelector('.pal-it.on').textContent"))
        await pg.keyboard.press('Enter'); await pg.wait_for_timeout(900)
        ok('Enter opens the selected partnership', await E("App.route.name") == 'partnership' and not await E("!!document.querySelector('#pal')"))
        await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(400)
        ok('recently opened appears first', await E("document.querySelector('.pal-h').textContent") == 'فتحته مؤخرًا')
        await pg.keyboard.type('شراكة جديدة'); await pg.wait_for_timeout(400); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(900)
        ok('runs an action (new partnership form)', await E("App.route.name") == 'pform')
        await go('#/partnerships')
        await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(300); await pg.keyboard.type('كلمةغيرموجودةابدا'); await pg.wait_for_timeout(400)
        ok('no results state', await E("!!document.querySelector('.pal-empty')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        ok('Esc closes the window', not await E("!!document.querySelector('#pal')"))
        await pg.click('.bo-find'); await pg.wait_for_timeout(300)
        ok('header search button opens the same window', await E("!!document.querySelector('#pal')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await E("D.settings.session={role:'viewer'}; renderShell()"); await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(300)
        ok('actions respect the role (viewer sees no «new partnership»)', 'شراكة جديدة' not in await E("document.querySelector('#palRes').textContent"))
        await pg.keyboard.press('Escape'); await E("D.settings.session={role:'admin'}; renderShell()"); await pg.wait_for_timeout(300)
        # — الترويسة —
        ok('«جديد» menu with four shortcuts', await E("document.querySelectorAll('.bo-new .bo-new-i').length") == 4)
        await pg.click('.bo-more .st-ddt'); await pg.wait_for_timeout(300)
        ok('«المزيد» opens a grouped menu', await E("document.querySelectorAll('.bo-mega .bo-mega-g').length") >= 2)
        await pg.click('.bo-mega a[href="#/media"]'); await pg.wait_for_timeout(900)
        ok('menu link navigates and marks «المزيد» active', await E("App.route.name") == 'media' and await E("document.querySelector('.bo-more').classList.contains('on')"))
        ind = await E("(()=>{const i=document.querySelector('.bo-ind'),a=document.querySelector('.bo-more>.bo-link');const ir=i.getBoundingClientRect(),ar=a.getBoundingClientRect();return [getComputedStyle(i).opacity, Math.abs((ir.left+ir.right)/2-(ar.left+ar.right)/2)]})()")
        await pg.wait_for_timeout(600)
        ind = await E("(()=>{const i=document.querySelector('.bo-ind'),a=document.querySelector('.bo-more>.bo-link');const ir=i.getBoundingClientRect(),ar=a.getBoundingClientRect();return [getComputedStyle(i).opacity, Math.abs((ir.left+ir.right)/2-(ar.left+ar.right)/2)]})()")
        ok('gold indicator slides under the active item', ind[0] == '1' and ind[1] < 3, ind)
        await go('#/media?upload=1'); await pg.wait_for_timeout(500)
        ok('«رفع صور» shortcut opens the upload dialog', await E("!!document.querySelector('#muDrop')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        # — الصفحات —
        await go('#/partners')
        ok('page header shows its section line', await E("document.querySelector('.ph .bo-ph-eye').textContent") == 'الشراكات')
        await go('#/partnerships')
        ok('status strip above the register', await E("document.querySelectorAll('#regStrip .bo-sst').length") >= 4)
        soon = await E("visiblePartnerships().filter(p=>pStatus(p)==='soon').length")
        await pg.click('[data-sst="soon"]'); await pg.wait_for_timeout(400)
        ok('strip filters the register in one click', await E("App.lastRegList.length") == soon and 'status=soon' in await E("location.hash"))
        ok('active strip item and filter bar stay in sync', await E("document.querySelector('.bo-sst.on').dataset.sst") == 'soon' and await E("!!document.querySelector('#regF .fbtn.on')"))
        await pg.click('[data-sst=""]'); await pg.wait_for_timeout(400)
        ok('«الكل» clears the status filter', await E("App.lastRegList.length") == await E("visiblePartnerships().length"))
        pid = await E("D.partnerships[2].id"); await go(f'#/partnerships/{pid}')
        ok('partnership cover title is white on the photo (readable)', await E("getComputedStyle(document.querySelector('.dhead h1')).color") == 'rgb(255, 255, 255)')
        await go('#/')
        ok('home: daily shortcuts under the hero', await E("document.querySelectorAll('.bo-quick .bo-qt').length") >= 5)
        ok('shortcuts show pending work (expiring)', 'تنتهي' in await E("document.querySelector('.bo-quick').textContent"))
        await pg.click('.bo-qt.find'); await pg.wait_for_timeout(300)
        ok('«ابحث في كل شيء» tile opens the window', await E("!!document.querySelector('#pal')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # — الاتجاهات الأخرى —
        await E("applyDesign('classic')"); await pg.wait_for_timeout(900)
        await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(300)
        ok('Ctrl+K works in other directions too', await E("!!document.querySelector('#pal')"))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        await go('#/partnerships')
        ok('status strip only in the board direction', not await E("!!document.querySelector('#regStrip')"))
        await E("applyDesign('board')"); await pg.wait_for_timeout(900)
        await pg.set_viewport_size({'width':390,'height':844})
        for h in ['#/', '#/partnerships', '#/dashboard?v=alt', '#/media', '#/process']:
            await go(h)
            ok(f'mobile {h}: header fits, no horizontal scroll', await E("document.documentElement.scrollWidth<=innerWidth+1 && [...document.querySelectorAll('.bo-row1 > *, .bo-tools > *')].filter(e=>getComputedStyle(e).display!=='none').every(e=>{const r=e.getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1})"))
        ok('no page errors', not errs, errs[:3])
        await b.close()
    print(f'\n{sum(R)}/{len(R)} passed')
asyncio.run(main())
